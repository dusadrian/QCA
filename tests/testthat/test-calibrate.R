local_edition(3)
set.seed(30)
x <- rnorm(30)
th <- as.vector(quantile(x, seq(from = 0.1, to = 0.9, length = 5)))


set.seed(12345)
y <- rnorm(n = 100, mean = 175, sd = 10)


test_that("tests for calibrate() have the same output", {
  expect_snapshot(calibrate(x, type = "crisp", thresholds = th[3]))
  expect_snapshot(calibrate(x, type = "crisp", thresholds = th[3]))
  expect_snapshot(calibrate(x, type = "crisp", thresholds = c(th[2], th[4])))
  expect_snapshot(calibrate(x, type = "fuzzy", thresholds = c(th[1], th[3], th[5]), logistic = FALSE))
  expect_snapshot(calibrate(x, type = "fuzzy", thresholds = c(th[1], th[3], th[5]), idm = 0.99))
  expect_snapshot(calibrate(x, type = "fuzzy", thresholds = c(th[5], th[3], th[1]), idm = 0.99))
  expect_snapshot(calibrate(x, type = "fuzzy", thresholds = c(th[1], th[3], th[5]), logistic = FALSE, ecdf = TRUE))
  expect_snapshot(calibrate(x, type = "fuzzy", thresholds = c(th[5], th[3], th[1]), logistic = FALSE, p = 2, q = 2))
  expect_snapshot(calibrate(x, type = "fuzzy", thresholds = th[c(1,2,3,3,4,5)], logistic = FALSE))
  expect_snapshot(calibrate(x, type = "fuzzy", thresholds = th[c(3,2,1,5,4,3)], logistic = FALSE))
  expect_snapshot(calibrate(y, type = "crisp", thresholds = 175))
  expect_snapshot(calibrate(y, type = "crisp", thresholds = c(170, 180)))
  expect_snapshot(calibrate(y, type = "fuzzy", thresholds = "e=165, c=175, i=185"))
  expect_snapshot(calibrate(y, type = "fuzzy", thresholds = "i=165, c=175, e=185"))
  expect_snapshot(calibrate(y, type = "fuzzy", logistic = FALSE, thresholds = "e=165, c=175, i=185"))
  expect_snapshot(calibrate(y, type = "fuzzy", logistic = FALSE, above = 3.5, below = 3.5, thresholds = "e=155, c=175, i=195"))
  expect_snapshot(calibrate(y, type = "fuzzy", below = 3, above = 3, thresholds = "e1=155, c1=165, i1=175, i2=175, c2=185, e2=195"))
  expect_snapshot(calibrate(y, type = "fuzzy", below = 3, above = 3, thresholds = "i1=155, c1=165, e1=175, e2=175, c2=185, i2=195"))
  expect_snapshot(calibrate(y, type = "fuzzy", thresholds = "e1=155, c1=165, i1=175, i2=175, c2=185, e2=195"))
  expect_snapshot(calibrate(y, type = "fuzzy", below = 10, above = 10, thresholds = "e1=155, c1=165, i1=175, i2=175, c2=185, e2=195"))
  expect_snapshot(calibrate(y, type = "fuzzy", below = 10000, above = 10000, thresholds = "e1=155, c1=165, i1=175, i2=175, c2=185, e2=195"))
  expect_snapshot(calibrate(y, type = "fuzzy", logistic = FALSE, ecdf = TRUE, thresholds = "e=155, c=175, i=195"))
})
